"""
Generates frontend_v2/items/tesla/MapCoverage.js: where MML's orthophoto has imagery, for
TeslaMap and TripMap to fall back to EOX outside it (#59).

MML covers Finland's land, Åland and some of the sea off the coast, and answers anywhere
else with a blank white tile. The outline is Finland and Åland from Natural Earth's 1:10m
countries (public domain), widened a little out to sea and kept back from the land borders,
where MML's imagery stops at the border and Natural Earth's border is a kilometre or so off:
inside the coverage, so a view the outline holds has imagery everywhere. Sampled at zoom 14
along the outline (a blank is exactly 668 bytes of white; open water is a small but blue
tile), every point had imagery at 3 km out and 3 km back; at 5 km and more out, points off
the Ostrobothnian coast and west of Åland were blank.

Run once, from a directory of its own, with the countries file downloaded beside nothing else:
    curl -LO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_10m_admin_0_countries.geojson
    uv run --with shapely --with pyproj python -I scripts/gen-map-coverage.py \\
        ne_10m_admin_0_countries.geojson frontend_v2/items/tesla/MapCoverage.js
"""
import json
import sys

import shapely
from pyproj import Transformer
from shapely.geometry import shape, MultiPolygon
from shapely.ops import unary_union

SEA_MARGIN_M = 3000
BORDER_MARGIN_M = 3000
SIMPLIFY_M = 300
# Pieces smaller than this after widening are dropped: a lone skerry far out at sea.
MIN_AREA_M2 = 20e6


def main(countries_path: str, out_path: str) -> None:
    '''
    Writes the coverage outline as a QML JavaScript library.
    Arguments:
        countries_path (str): Natural Earth's ne_10m_admin_0_countries.geojson.
        out_path (str): The MapCoverage.js to write.
    '''
    features = json.load(open(countries_path, encoding="utf-8"))["features"]
    by_code = {f["properties"]["ADM0_A3"]: shape(f["geometry"]) for f in features}
    # ETRS-TM35FIN, so the margin is in metres everywhere in Finland.
    to_m = Transformer.from_crs("EPSG:4326", "EPSG:3067", always_xy=True).transform
    to_deg = Transformer.from_crs("EPSG:3067", "EPSG:4326", always_xy=True).transform

    def metres(geometry):
        return shapely.transform(geometry, to_m, interleaved=False)

    finland = metres(unary_union([by_code["FIN"], by_code["ALD"]]))
    neighbours = metres(unary_union([by_code[c] for c in ("SWE", "NOR", "RUS")]))
    outline = finland.buffer(SEA_MARGIN_M).difference(neighbours.buffer(BORDER_MARGIN_M))
    outline = outline.simplify(SIMPLIFY_M, preserve_topology=True)
    parts = outline.geoms if isinstance(outline, MultiPolygon) else [outline]
    rings = []
    for part in sorted(parts, key=lambda p: -p.area):
        if part.area < MIN_AREA_M2:
            continue
        # The exterior only: a hole would be a lake, which MML covers.
        lonlat = (to_deg(x, y) for x, y in part.exterior.coords)
        rings.append([v for lon, lat in lonlat for v in (round(lat, 3), round(lon, 3))])

    points = sum(len(r) // 2 for r in rings)
    with open(out_path, "w", encoding="utf-8") as out:
        out.write(".pragma library\n\n")
        out.write(f"// Where MML's orthophoto has imagery: Finland and Åland widened {SEA_MARGIN_M // 1000} km out to\n")
        out.write(f"// sea and kept {BORDER_MARGIN_M // 1000} km back from the land borders. Generated by\n")
        out.write("// scripts/gen-map-coverage.py from Natural Earth (public domain); do not edit by hand.\n")
        out.write(f"// {len(rings)} rings, {points} points, each ring flat as [lat, lon, lat, lon, …].\n")
        out.write("var RINGS = [\n")
        for ring in rings:
            out.write("    [" + ",".join(f"{v:g}" for v in ring) + "],\n")
        out.write("]\n\n")
        out.write('''// The edges by latitude band, built on first use: a point tests only the edges that cross
// its latitude, a few dozen of the outline's points rather than all of them.
var BAND = 0.05
var bands = null
var minLat = 0

function index() {
    minLat = Infinity
    var maxLat = -Infinity
    for (var r = 0; r < RINGS.length; r++)
        for (var i = 0; i < RINGS[r].length; i += 2) {
            minLat = Math.min(minLat, RINGS[r][i])
            maxLat = Math.max(maxLat, RINGS[r][i])
        }
    bands = []
    for (var b = 0; b <= Math.floor((maxLat - minLat) / BAND); b++)
        bands.push([])
    for (r = 0; r < RINGS.length; r++) {
        var ring = RINGS[r]
        for (var k = 0, j = ring.length - 2; k < ring.length; j = k, k += 2) {
            var lo = Math.floor((Math.min(ring[k], ring[j]) - minLat) / BAND)
            var hi = Math.floor((Math.max(ring[k], ring[j]) - minLat) / BAND)
            for (b = lo; b <= hi; b++)
                bands[b].push(ring[k], ring[k + 1], ring[j], ring[j + 1])
        }
    }
}

// Even-odd point-in-polygon over every ring.
function covers(lat, lon) {
    if (!bands)
        index()
    var b = Math.floor((lat - minLat) / BAND)
    if (b < 0 || b >= bands.length)
        return false
    var edges = bands[b]
    var inside = false
    for (var k = 0; k < edges.length; k += 4) {
        var yi = edges[k], xi = edges[k + 1], yj = edges[k + 2], xj = edges[k + 3]
        if ((yi > lat) !== (yj > lat) && lon < (xj - xi) * (lat - yi) / (yj - yi) + xi)
            inside = !inside
    }
    return inside
}
''')
    print(f"{len(rings)} rings, {points} points -> {out_path}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
